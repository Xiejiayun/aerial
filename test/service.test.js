function makeRunner() {
  const calls = [];
  const queue = [];
  function run(file, args, opts) {
    calls.push({ file, args, opts });
    const next = queue.shift();
    if (next) return next;
    return { status: 0, stdout: "", stderr: "" };
  }
  run.calls = calls;
  run.queue = queue;
  return run;
}

function absentHealth() {
  return async () => ({ ok: false, error: "ECONNREFUSED" });
}

function aerialHealth() {
  return async () => ({ ok: true, status: 200, body: { ok: true, service: "aerial" } });
}

function nonAerialHealth() {
  return async () => ({ ok: true, status: 200, body: { ok: true, service: "something-else" } });
}

function parseFailHealth() {
  return async () => ({ ok: true, status: 200, parseFailed: true });
}

function healthSequence(...probes) {
  let i = 0;
  return async () => {
    const next = probes[Math.min(i, probes.length - 1)];
    i += 1;
    if (typeof next === "function") return next();
    return next;
  };
}

