function cleanupServiceArtifacts() {
  try {
    const p = _internal.plistPath();
    if (fs.existsSync(p)) fs.unlinkSync(p);
  } catch {}
  try {
    const w = process.platform === "darwin" ? _internal.darwinWrapperPath() : _internal.winWrapperPath();
    if (fs.existsSync(w)) fs.unlinkSync(w);
  } catch {}
}

