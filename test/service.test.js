test("serviceInstall on managed+running refreshes definition (does NOT short-circuit) and does NOT start a second service", { skip: process.platform !== "darwin" && process.platform !== "win32" }, async () => {
  cleanupServiceArtifacts();
  if (process.platform === "darwin") {
    fs.mkdirSync(path.dirname(_internal.plistPath()), { recursive: true });
    fs.writeFileSync(_internal.plistPath(), "<placeholder/>");
    fs.mkdirSync(path.dirname(_internal.darwinWrapperPath()), { recursive: true });
    fs.writeFileSync(_internal.darwinWrapperPath(), "#!/bin/sh\n# placeholder\n");
  } else {
    fs.mkdirSync(path.dirname(_internal.winWrapperPath()), { recursive: true });
    fs.writeFileSync(_internal.winWrapperPath(), "rem placeholder");
  }
  const run = makeRunner();
  if (process.platform === "darwin") {
    run.queue.push({ status: 0, stdout: "{\n\t\"PID\" = 1234;\n};", stderr: "" });
  } else {
    run.queue.push({ status: 0, stdout: "TaskName: \\AerialLocalProxy\r\nStatus: Running", stderr: "" });
    run.queue.push({ status: 0, stdout: "", stderr: "" });
  }
  const result = await serviceInstall({ run, healthFetch: aerialHealth() });
  assert.equal(result.ok, true);
  assert.equal(result.definitionUpdated, true);
  assert.match(result.note, /definition refreshed/);
  assert.match(result.note, /aerial service restart/);
  if (process.platform === "darwin") {
    const plist = fs.readFileSync(_internal.plistPath(), "utf8");
    const wrapper = fs.readFileSync(_internal.darwinWrapperPath(), "utf8");
    assert.match(plist, /Generated by aerial/, "plist must be rewritten with real content, not preserved as placeholder");
    assert.match(wrapper, /^#!\/bin\/sh/);
    assert.match(wrapper, /Generated by aerial/, "wrapper must be rewritten, not left as placeholder");
    assert.ok(!run.calls.find((c) => c.file === "launchctl" && c.args[0] === "bootstrap"), "must not bootstrap a second service");
  } else {
    const wrapper = fs.readFileSync(_internal.winWrapperPath(), "utf8");
    assert.match(wrapper, /Generated by aerial/, "wrapper must be rewritten, not left as placeholder");
    assert.ok(run.calls.find((c) => c.file === "schtasks.exe" && c.args.includes("/Create")), "must regenerate via schtasks /Create");
    assert.ok(!run.calls.find((c) => c.file === "schtasks.exe" && c.args.includes("/Run")), "must not /Run a second instance");
  }
  cleanupServiceArtifacts();
});

